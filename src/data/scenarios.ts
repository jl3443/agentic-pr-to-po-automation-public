function makeAgentExecutions(completedUpTo: number): AgentExecution[] {
  const agents: AgentExecution[] = [
    { agentId: 'content-extraction', label: 'Content Extraction', status: 'pending', fieldsProcessed: 18 },
    { agentId: 'scenario-identification', label: 'Scenario Identification', status: 'pending', confidence: 94 },
    { agentId: 'validation', label: 'Validation', status: 'pending', fieldsProcessed: 16 },
    { agentId: 'po-creation', label: 'PO Creation', status: 'pending', fieldsProcessed: 22 },
    { agentId: 'po-release', label: 'PO Release', status: 'pending' },
    { agentId: 'ticket-updation', label: 'Ticket Updation', status: 'pending' },
  ];
  for (let i = 0; i < agents.length; i++) {
    if (i < completedUpTo) {
      agents[i].status = 'complete';
      agents[i].duration = `${(1.2 + Math.random() * 2.5).toFixed(1)}s`;
    } else if (i === completedUpTo) {
      agents[i].status = 'running';
    }
  }
  return agents;
}

